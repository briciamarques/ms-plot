// Rebuild the site's saved measurements from the original powermeter ZIPs.
// Usage: node scripts/update_power_defaults.mjs <280nm.zip> <365nm.zip>
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';
import ts from 'typescript';

const inputs = process.argv.slice(2);
if (!inputs.length) throw Error('Provide the complete calibration ZIPs to bundle.');
const temp = path.resolve('node_modules/.tmp/power-defaults');
fs.mkdirSync(temp, {recursive: true});
fs.writeFileSync(path.join(temp, 'parser.mjs'), ts.transpileModule(fs.readFileSync('src/utils/powerCalibration.ts', 'utf8'), {
  compilerOptions: {target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020},
}).outputText);
const {readPowerUploads, defaultPowerCalibration, validatePowerCalibration, summarizePower} = await import(pathToFileURL(path.join(temp, 'parser.mjs')));
const measurements = [], sources = [];
for (const input of inputs) {
  const bytes = fs.readFileSync(input);
  const name = path.basename(input);
  measurements.push(...await readPowerUploads([{name, size: bytes.length, arrayBuffer: async () => bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength)}]));
  sources.push({filename: name, sha256: createHash('sha256').update(bytes).digest('hex')});
}
const config = validatePowerCalibration({...defaultPowerCalibration(measurements), enabled: true, automaticWavelength: true});
for (const wavelength of new Set(measurements.map(m => m.wavelengthNm))) {
  const profile = defaultPowerCalibration(measurements.filter(m => m.wavelengthNm === wavelength));
  const summary = summarizePower(profile);
  if (summary.error) throw Error(`${wavelength} nm: ${summary.error}`);
  console.log(`${wavelength} nm: ${profile.intervalSeconds} s, ${summary.points.length} currents, initial background ${summary.backgroundMw} mW`);
}
fs.mkdirSync('src/data', {recursive: true});
fs.writeFileSync('src/data/powerMeasurements.ts', '// Generated by scripts/update_power_defaults.mjs; original readings in W.\nimport type {PowerCalibration} from "../utils/powerCalibration";\n' +
  `export const powerSources = ${JSON.stringify(sources, null, 2)};\n` +
  `export const savedPowerCalibration: PowerCalibration = ${JSON.stringify(config, null, 2)};\n`);
console.log(`Saved ${measurements.length} CSV records.`);
